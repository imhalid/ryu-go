// Gentokens, Mizan'ın tokens.json dosyasından tokens_gen.go'yu üretir. Tek
// kaynak tokens.json'dır: web kütüphanesi ile native kütüphane aynı değerleri
// okur, elle kopyalanan değer yoktur.
//
//	go run ./internal/gentokens -in ../../pano-ui/src/styles/tokens.json -out tokens_gen.go
//
// Renkler, gölgeler, boyut kademeleri, yazı ölçeği ve yazı stilleri üretilir.
// Gradyan, doku ve içerik değerleri (control, grain, led, switch-on) Go'da elle
// çizilir; üreteç bunları atlar.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type token struct {
	Name  string          `json:"name"`
	Value json.RawMessage `json:"value"`
	Usage string          `json:"usage"`
}

type typeStyle struct {
	Name          string  `json:"name"`
	FontSize      string  `json:"fontSize"`
	LineHeight    float64 `json:"lineHeight"`
	FontWeight    int     `json:"fontWeight"`
	LetterSpacing string  `json:"letterSpacing"`
	Usage         string  `json:"usage"`
}

type file struct {
	Color   struct{ Tokens []token } `json:"color"`
	Spacing struct{ Tokens []token } `json:"spacing"`
	Radius  struct{ Tokens []token } `json:"radius"`
	Shadow  struct{ Tokens []token } `json:"shadow"`
	Size    struct {
		Levels []string `json:"levels"`
		Tokens []token  `json:"tokens"`
	} `json:"size"`
	Type struct {
		Scale  struct{ Tokens []token } `json:"scale"`
		Groups []struct {
			Family string      `json:"family"`
			Styles []typeStyle `json:"styles"`
		} `json:"groups"`
	} `json:"type"`
	Skin struct {
		Skins map[string]struct{ Tokens []token } `json:"skins"`
	} `json:"skin"`
}

// gen, bir malzeme ve temada değer çözen durumdur.
type gen struct {
	f      file
	colors map[string]token
	shadow map[string]token
	skin   map[string]map[string]token
	// lengths: boyut kademesinden bağımsız uzunluklar (radius, spacing, fs).
	lengths map[string]float64
}

// skins: malzemelerin Go'daki sırası; Skin sabitleriyle aynı.
var skins = []string{"mizan", "bevel"}

var themes = []string{"light", "dark"}

func main() {
	in := flag.String("in", "", "tokens.json")
	out := flag.String("out", "tokens_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	g := &gen{colors: map[string]token{}, shadow: map[string]token{}, skin: map[string]map[string]token{}, lengths: map[string]float64{}}
	if err := json.Unmarshal(data, &g.f); err != nil {
		log.Fatal(err)
	}
	for _, t := range g.f.Color.Tokens {
		g.colors[t.Name] = t
	}
	for _, t := range g.f.Shadow.Tokens {
		g.shadow[t.Name] = t
	}
	for name, s := range g.f.Skin.Skins {
		m := map[string]token{}
		for _, t := range s.Tokens {
			m[t.Name] = t
		}
		g.skin[name] = m
	}
	for _, t := range g.f.Type.Scale.Tokens {
		g.lengths[t.Name] = mustPx(str(t.Value))
	}
	for _, t := range g.f.Spacing.Tokens {
		g.lengths[t.Name] = mustPx(str(t.Value))
	}
	for _, t := range g.f.Radius.Tokens {
		if t.Name == "radius-inner" {
			continue
		}
		g.lengths[t.Name] = mustPx(str(t.Value))
	}
	// radius-inner = max(0px, calc(var(--radius-control) - 3px))
	g.lengths["radius-inner"] = max(0, g.lengths["radius-control"]-3)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gentokens from tokens.json; DO NOT EDIT.\n\npackage mizan\n\nimport \"github.com/egoist/mygo/ui\"\n\n")
	g.writeLengths(&b)
	g.writeColors(&b)
	g.writeShadows(&b)
	g.writeMetrics(&b)
	g.writeTypes(&b)
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(*out, b.Bytes(), 0o644)
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func (g *gen) writeLengths(b *bytes.Buffer) {
	b.WriteString("// Yazı ölçeği, aralıklar ve köşe yarıçapları (DIP). Boyut kademesinden bağımsızdır.\nconst (\n")
	groups := [][]token{g.f.Type.Scale.Tokens, g.f.Spacing.Tokens, g.f.Radius.Tokens}
	for _, ts := range groups {
		for _, t := range ts {
			comment(b, t.Usage)
			fmt.Fprintf(b, "%s = %s\n", ident(t.Name), num(g.lengths[t.Name]))
		}
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")
}

// colorNames, Colors yapısının alanlarıdır: renk token'ları ve malzemelerin
// renk olarak çözülen kendi token'ları (bevel-hi, raised, led-color…).
func (g *gen) colorNames() []string {
	var names []string
	seen := map[string]bool{}
	for _, t := range g.f.Color.Tokens {
		names = append(names, t.Name)
		seen[t.Name] = true
	}
	var extra []string
	for _, s := range skins[1:] {
		for name := range g.skin[s] {
			if seen[name] || g.shadow[name].Name != "" || name == "switch-on-glow" {
				continue
			}
			if _, err := g.color(name, s, "light"); err != nil {
				continue
			}
			seen[name] = true
			extra = append(extra, name)
		}
	}
	sort.Strings(extra)
	return append(names, extra...)
}

func (g *gen) writeColors(b *bytes.Buffer) {
	names := g.colorNames()
	b.WriteString("// Colors, bir malzeme ve temadaki renk rolleridir.\ntype Colors struct {\n")
	for _, n := range names {
		comment(b, g.usage(n))
		fmt.Fprintf(b, "%s ui.Color\n", ident(n))
	}
	b.WriteString("}\n\n")
	b.WriteString("// genColors[malzeme][tema]: tema 0 açık, 1 koyu.\nvar genColors = [skinCount][2]Colors{\n")
	for _, s := range skins {
		b.WriteString("{\n")
		for _, th := range themes {
			b.WriteString("{\n")
			for _, n := range names {
				expr, err := g.color(n, s, th)
				if err != nil {
					// malzemenin yardımcı rengi varsayılan malzemede yoktur
					continue
				}
				fmt.Fprintf(b, "%s: %s,\n", ident(n), expr)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func (g *gen) shadowNames() []string {
	var names []string
	for _, t := range g.f.Shadow.Tokens {
		names = append(names, t.Name)
	}
	return append(names, "switch-on-glow")
}

func (g *gen) writeShadows(b *bytes.Buffer) {
	names := g.shadowNames()
	b.WriteString("// Shadows, bir malzeme ve temadaki katmanlı gölgelerdir (CSS box-shadow).\ntype Shadows struct {\n")
	for _, n := range names {
		comment(b, g.usage(n))
		fmt.Fprintf(b, "%s Shadow\n", ident(n))
	}
	b.WriteString("}\n\nvar genShadows = [skinCount][2]Shadows{\n")
	for _, s := range skins {
		b.WriteString("{\n")
		for _, th := range themes {
			b.WriteString("{\n")
			for _, n := range names {
				expr, err := g.shadowValue(n, s, th)
				if err != nil {
					log.Fatalf("shadow %s (%s, %s): %v", n, s, th, err)
				}
				if expr != "nil" {
					fmt.Fprintf(b, "%s: %s,\n", ident(n), expr)
				}
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func (g *gen) writeMetrics(b *bytes.Buffer) {
	b.WriteString("// Metrics, bir boyut kademesindeki ölçülerdir (DIP). Sıfır yazı boyutu çevreden\n// kalıtılır (CSS'te initial); harf aralığı (…Ls) em cinsindendir.\ntype Metrics struct {\n")
	for _, t := range g.f.Size.Tokens {
		comment(b, t.Usage)
		fmt.Fprintf(b, "%s float32\n", ident(t.Name))
	}
	b.WriteString("}\n\n// genMetrics[kademe]: 0 sm, 1 md, 2 lg.\nvar genMetrics = [3]Metrics{\n")
	for _, lv := range g.f.Size.Levels {
		b.WriteString("{\n")
		for _, t := range g.f.Size.Tokens {
			v, err := g.sizeValue(t.Name, lv, 0)
			if err != nil {
				log.Fatalf("size %s (%s): %v", t.Name, lv, err)
			}
			fmt.Fprintf(b, "%s: %s,\n", ident(t.Name), num(v))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func (g *gen) writeTypes(b *bytes.Buffer) {
	b.WriteString("// Yazı stilleri (tokens.json › type).\nvar (\n")
	for _, gr := range g.f.Type.Groups {
		for _, s := range gr.Styles {
			size, err := g.length(s.FontSize)
			if err != nil {
				log.Fatalf("type %s: %v", s.Name, err)
			}
			ls := 0.0
			if s.LetterSpacing != "" {
				ls = mustEm(s.LetterSpacing)
			}
			comment(b, s.Usage)
			fmt.Fprintf(b, "%s = TypeStyle{Size: %s, LineHeight: %s, Weight: %d, Tracking: %s, Mono: %v}\n",
				ident(s.Name), num(size), num(s.LineHeight), s.FontWeight, num(ls), gr.Family == "mono")
		}
	}
	b.WriteString(")\n")
}

// lookup, adı önce malzemenin kendi token'larında, sonra varsayılanlarda arar.
func (g *gen) lookup(name, skin string) (token, bool) {
	if t, ok := g.skin[skin][name]; ok && skin != "mizan" {
		return t, true
	}
	if t, ok := g.colors[name]; ok {
		return t, true
	}
	if t, ok := g.shadow[name]; ok {
		return t, true
	}
	return token{}, false
}

func (g *gen) usage(name string) string {
	if t, ok := g.colors[name]; ok {
		return t.Usage
	}
	if t, ok := g.shadow[name]; ok {
		return t.Usage
	}
	for _, s := range skins[1:] {
		if t, ok := g.skin[s][name]; ok {
			return t.Usage
		}
	}
	return ""
}

// themed, {light, dark} biçimli değerden temanın değerini, düz değerden
// kendisini verir.
func themed(raw json.RawMessage, theme string) string {
	var m map[string]string
	if json.Unmarshal(raw, &m) == nil {
		return m[theme]
	}
	return str(raw)
}

func (g *gen) color(name, skin, theme string) (string, error) {
	// malzemenin renk olmayan değeri (bevel'de thumb bir gradyandır) Go'da
	// elle çizilir; Colors alanı varsayılan malzemenin rengini taşır
	if t, ok := g.skin[skin][name]; ok && skin != "mizan" {
		if e, err := g.colorExpr(themed(t.Value, theme), skin, theme); err == nil {
			return e, nil
		}
	}
	t, ok := g.colors[name]
	if !ok {
		return "", fmt.Errorf("unknown color %q", name)
	}
	return g.colorExpr(themed(t.Value, theme), skin, theme)
}

var (
	reRef    = regexp.MustCompile(`^\{([\w-]+)\}$`)
	reVar    = regexp.MustCompile(`^var\(--([\w-]+)\)$`)
	reOklch  = regexp.MustCompile(`^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*(?:/\s*([\d.]+)%)?\s*\)$`)
	reMix    = regexp.MustCompile(`^color-mix\(\s*in oklab\s*,(.*)\)$`)
	rePct    = regexp.MustCompile(`^(.*?)\s+([\d.]+)%$`)
	reLength = regexp.MustCompile(`^-?[\d.]+(px)?$`)
)

// colorExpr, bir CSS renk ifadesini Go ifadesine çevirir.
func (g *gen) colorExpr(s, skin, theme string) (string, error) {
	s = strings.TrimSpace(s)
	if s == "transparent" {
		return "ui.Color{}", nil
	}
	if m := reRef.FindStringSubmatch(s); m != nil {
		return g.color(m[1], skin, theme)
	}
	if m := reVar.FindStringSubmatch(s); m != nil {
		return g.color(m[1], skin, theme)
	}
	if m := reOklch.FindStringSubmatch(s); m != nil {
		l, _ := strconv.ParseFloat(m[1], 64)
		a := 100.0
		if m[4] != "" {
			a, _ = strconv.ParseFloat(m[4], 64)
		}
		return fmt.Sprintf("oklch(%s, %s, %s, %s)", num(l/100), m[2], m[3], num(a/100)), nil
	}
	if m := reMix.FindStringSubmatch(s); m != nil {
		args := split(m[1], ',')
		if len(args) != 2 {
			return "", fmt.Errorf("color-mix: %q", s)
		}
		a, pa := percent(args[0])
		bb, pb := percent(args[1])
		// t: ikinci rengin payı (CSS: verilmeyen pay kalandır, ikisi de yoksa yarı yarıya)
		t := 0.5
		switch {
		case pa >= 0 && pb >= 0:
			t = pb / (pa + pb)
		case pa >= 0:
			t = 1 - pa
		case pb >= 0:
			t = pb
		}
		ea, err := g.colorExpr(a, skin, theme)
		if err != nil {
			return "", err
		}
		eb, err := g.colorExpr(bb, skin, theme)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("Mix(%s, %s, %s)", ea, eb, num(t)), nil
	}
	return "", fmt.Errorf("not a color: %q", s)
}

// percent, "renk 40%" biçiminden rengi ve payı (0–1) verir; pay yoksa -1.
func percent(s string) (string, float64) {
	s = strings.TrimSpace(s)
	if m := rePct.FindStringSubmatch(s); m != nil && !strings.HasSuffix(m[1], "/") {
		p, _ := strconv.ParseFloat(m[2], 64)
		return m[1], p / 100
	}
	return s, -1
}

func (g *gen) shadowValue(name, skin, theme string) (string, error) {
	var raw json.RawMessage
	if t, ok := g.skin[skin][name]; ok && skin != "mizan" {
		raw = t.Value
	} else if t, ok := g.shadow[name]; ok {
		raw = t.Value
	} else {
		// varsayılan malzemede yalnız bevel'in tanımladığı gölge (switch-on-glow)
		return "nil", nil
	}
	layers, err := g.shadowLayers(themed(raw, theme), skin, theme)
	if err != nil {
		return "", err
	}
	if len(layers) == 0 {
		return "nil", nil
	}
	return "Shadow{" + strings.Join(layers, ", ") + "}", nil
}

func (g *gen) shadowLayers(s, skin, theme string) ([]string, error) {
	s = strings.TrimSpace(s)
	if s == "none" {
		return nil, nil
	}
	var out []string
	for _, part := range split(s, ',') {
		part = strings.TrimSpace(part)
		if m := reVar.FindStringSubmatch(part); m != nil {
			// başka bir gölgeye başvuru: katmanları araya girer
			t, ok := g.lookup(m[1], skin)
			if !ok {
				return nil, fmt.Errorf("unknown shadow %q", m[1])
			}
			sub, err := g.shadowLayers(themed(t.Value, theme), skin, theme)
			if err != nil {
				return nil, err
			}
			out = append(out, sub...)
			continue
		}
		fields := split(part, ' ')
		inset := false
		var lens []float64
		var color []string
		for _, f := range fields {
			switch {
			case f == "inset":
				inset = true
			case reLength.MatchString(f) && len(color) == 0:
				lens = append(lens, mustPx(f))
			default:
				color = append(color, f)
			}
		}
		if len(lens) < 2 || len(color) == 0 {
			return nil, fmt.Errorf("shadow layer %q", part)
		}
		for len(lens) < 4 {
			lens = append(lens, 0)
		}
		c, err := g.colorExpr(strings.Join(color, " "), skin, theme)
		if err != nil {
			return nil, err
		}
		out = append(out, fmt.Sprintf("{X: %s, Y: %s, Blur: %s, Spread: %s, Color: %s, Inset: %v}",
			num(lens[0]), num(lens[1]), num(lens[2]), num(lens[3]), c, inset))
	}
	return out, nil
}

// sizeValue, bir boyut token'ını kademede sayıya çözer.
func (g *gen) sizeValue(name, level string, depth int) (float64, error) {
	if depth > 8 {
		return 0, fmt.Errorf("cycle at %q", name)
	}
	for _, t := range g.f.Size.Tokens {
		if t.Name != name {
			continue
		}
		var m map[string]string
		if err := json.Unmarshal(t.Value, &m); err != nil {
			return 0, err
		}
		v := strings.TrimSpace(m[level])
		switch {
		case v == "initial" || v == "normal":
			return 0, nil
		case strings.HasSuffix(v, "em"):
			return mustEm(v), nil
		}
		if r := reVar.FindStringSubmatch(v); r != nil {
			if _, ok := g.lengths[r[1]]; !ok {
				return g.sizeValue(r[1], level, depth+1)
			}
		}
		return g.length(v)
	}
	return 0, fmt.Errorf("unknown size token %q", name)
}

// length, px, {fs-*} ya da var(--…) uzunluğunu çözer.
func (g *gen) length(s string) (float64, error) {
	s = strings.TrimSpace(s)
	if m := reRef.FindStringSubmatch(s); m != nil {
		s = "var(--" + m[1] + ")"
	}
	if m := reVar.FindStringSubmatch(s); m != nil {
		v, ok := g.lengths[m[1]]
		if !ok {
			return 0, fmt.Errorf("unknown length %q", m[1])
		}
		return v, nil
	}
	if reLength.MatchString(s) {
		return mustPx(s), nil
	}
	return 0, fmt.Errorf("not a length: %q", s)
}

// split, s'yi parantez dışındaki sep'lerden böler.
func split(s string, sep byte) []string {
	var out []string
	depth, start := 0, 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			depth++
		case ')':
			depth--
		case sep:
			if depth == 0 {
				if p := strings.TrimSpace(s[start:i]); p != "" {
					out = append(out, p)
				}
				start = i + 1
			}
		}
	}
	if p := strings.TrimSpace(s[start:]); p != "" {
		out = append(out, p)
	}
	return out
}

func str(raw json.RawMessage) string {
	var s string
	if err := json.Unmarshal(raw, &s); err != nil {
		return string(raw)
	}
	return s
}

func mustPx(s string) float64 {
	v, err := strconv.ParseFloat(strings.TrimSuffix(strings.TrimSpace(s), "px"), 64)
	if err != nil {
		log.Fatalf("length %q: %v", s, err)
	}
	return v
}

func mustEm(s string) float64 {
	v, err := strconv.ParseFloat(strings.TrimSuffix(strings.TrimSpace(s), "em"), 64)
	if err != nil {
		log.Fatalf("em %q: %v", s, err)
	}
	return v
}

// num, değeri kayan nokta gürültüsü olmadan yazar (0.211, 0.21100000000000002 değil).
func num(v float64) string { return strconv.FormatFloat(math.Round(v*1e6)/1e6, 'f', -1, 64) }

// ident, kebab adı Go adına çevirir: color-accent-500 → ColorAccent500,
// t-title → TTitle, fs-2xs → Fs2xs.
func ident(name string) string {
	var b strings.Builder
	for _, p := range strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' }) {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func comment(b *bytes.Buffer, s string) {
	if s == "" {
		return
	}
	if r := []rune(s); len(r) > 110 {
		cut := strings.LastIndex(string(r[:110]), " ")
		if cut < 40 {
			cut = len(string(r[:110]))
		}
		s = s[:cut] + "…"
	}
	fmt.Fprintf(b, "// %s\n", s)
}
